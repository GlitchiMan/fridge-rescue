#!/usr/bin/env node
/**
 * Scans public/images and writes src/data/image-manifest.ts, so the app knows
 * which photos exist without ever requesting a missing file (no 404s, no
 * broken-image flashes, no layout shift).
 *
 *   public/images/<name>.<ext>            → site images (e.g. hero-kitchen.png)
 *   public/images/recipes/<slug>.<ext>    → recipe photos, named by recipe slug
 *
 * Runs automatically before `npm run dev` and `npm run build`.
 * Run `npm run images:sync` after adding images while the dev server is running.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, extname, join, basename } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const publicImages = join(root, "public", "images");
const out = join(root, "src", "data", "image-manifest.ts");

// Preferred order when several formats exist for the same name.
const EXTENSIONS = [".avif", ".webp", ".jpg", ".jpeg", ".png"];

function scan(dir, urlPrefix) {
  const result = {};
  if (!existsSync(dir)) return result;
  const files = readdirSync(dir, { withFileTypes: true }).filter((d) => d.isFile());
  for (const ext of EXTENSIONS) {
    for (const f of files) {
      if (extname(f.name).toLowerCase() !== ext) continue;
      const key = basename(f.name, extname(f.name)).toLowerCase();
      if (!(key in result)) result[key] = `${urlPrefix}/${f.name}`;
    }
  }
  return Object.fromEntries(Object.entries(result).sort(([a], [b]) => a.localeCompare(b)));
}

const site = scan(publicImages, "/images");
const recipes = scan(join(publicImages, "recipes"), "/images/recipes");

const content = `/**
 * GENERATED by scripts/sync-images.mjs – do not edit by hand.
 * Lists the images that actually exist in public/images.
 */
export const IMAGE_MANIFEST: {
  site: Record<string, string>;
  recipes: Record<string, string>;
} = ${JSON.stringify({ site, recipes }, null, 2)};
`;

const previous = existsSync(out) ? readFileSync(out, "utf8") : "";
if (previous !== content) writeFileSync(out, content);

console.log(
  `[images] site: ${Object.keys(site).join(", ") || "none"} · recipe photos: ${Object.keys(recipes).length}`,
);
